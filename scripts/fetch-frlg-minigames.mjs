// Reads FireRed's own Pokémon Jump out of pret's disassembly: who may jump,
// how each kind jumps, how the vine speeds up, what a jump scores and what a
// score wins. THE GAME CORNER's cabinet plays by these (`src/game/minigames/
// pokemonJump.ts`); nothing of it is typed out.
//
//   git clone --filter=blob:none --no-checkout https://github.com/pret/pokefirered.git /tmp/pokefirered
//   git -C /tmp/pokefirered sparse-checkout set --no-cone 'src/pokemon_jump.c'
//   git -C /tmp/pokefirered checkout 037335f4c725d7c9aecdac87066f2002b4bd7e14
//   node scripts/fetch-frlg-minigames.mjs /tmp/pokefirered
//
// It writes the committed snapshot `tools/minigames/frlg-pokemon-jump.json`
// and the generated module `src/game/minigames/generated/pokemonJump.ts`;
// `pokemonJump.test.ts` holds the one to the other, so a hand edit to either
// fails. Only Kanto's 151 are kept: FireRed's list runs on into Johto and
// Hoenn, whose kinds this game does not have.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const PRET_COMMIT = '037335f4c725d7c9aecdac87066f2002b4bd7e14';
const [pret] = process.argv.slice(2);
if (!pret) {
  console.error('usage: node scripts/fetch-frlg-minigames.mjs <pokefirered checkout>');
  process.exit(2);
}
const head = execFileSync('git', ['-C', pret, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (head !== PRET_COMMIT) {
  console.error(`the checkout is at ${head}, not ${PRET_COMMIT}`);
  process.exit(1);
}
const source = readFileSync(`${pret}/src/pokemon_jump.c`, 'utf8');

/** The body of a C initialiser `name[...] = { ... };`. */
function table(name) {
  const at = source.indexOf(`${name}[`);
  if (at < 0) throw new Error(`no ${name} in pokemon_jump.c`);
  const open = source.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < source.length; i += 1) {
    if (source[i] === '{') depth += 1;
    if (source[i] === '}') {
      depth -= 1;
      if (depth === 0) return source.slice(open + 1, i);
    }
  }
  throw new Error(`${name} never closes`);
}

const numbers = (text) => [...text.matchAll(/-?\d+/g)].map((match) => Number(match[0]));
const peak = Number(/#define JUMP_PEAK \((-?\d+)\)/.exec(source)[1]);

// Kanto's own kinds, by FireRed's name for them.
const kanto = JSON.parse(readFileSync(new URL('../tools/species/frlg-species.json', import.meta.url), 'utf8'));
const kantoIds = new Map(
  (Array.isArray(kanto) ? kanto : kanto.species ?? Object.values(kanto)).map((entry) => [
    String(entry.name ?? entry.id).toUpperCase().replace(/-/g, '_'),
    String(entry.name ?? entry.id),
  ]),
);

const mons = [...table('sPokeJumpMons').matchAll(/SPECIES_(\w+),\s*\.jumpType = JUMP_TYPE_(\w+)/g)]
  .map(([, species, type]) => ({ species, type: type.toLowerCase() }))
  .filter(({ species }) => kantoIds.has(species))
  .map(({ species, type }) => ({ species: kantoIds.get(species), type }));

const offsetsBody = table('sJumpOffsets').replace(/JUMP_PEAK/g, String(peak));
const arcs = Object.fromEntries(
  [...offsetsBody.matchAll(/\[JUMP_TYPE_(\w+)\]\s*=\s*\{([^}]*)\}/g)].map(([, type, body]) => [type.toLowerCase(), numbers(body)]),
);

const prizes = [...table('sPrizeQuantityData').matchAll(/\.score\s*=\s*(\d+),\s*\.quantity\s*=\s*(\d+)/g)].map(
  ([, score, quantity]) => ({ score: Number(score), quantity: Number(quantity) }),
);

const snapshot = {
  source: `pret/pokefirered ${PRET_COMMIT} src/pokemon_jump.c`,
  jumpPeak: peak,
  maxScore: Number(/#define MAX_JUMP_SCORE (\d+)/.exec(source)[1]),
  mons,
  arcs,
  vineBaseSpeeds: numbers(table('sVineBaseSpeeds')),
  vineSpeedDelays: numbers(table('sVineSpeedDelays')),
  scoreBonuses: numbers(table('sScoreBonuses')),
  prizes,
};
if (mons.length !== 32) throw new Error(`expected FireRed's 32 Kanto jumpers, read ${mons.length}`);

writeFileSync(new URL('../tools/minigames/frlg-pokemon-jump.json', import.meta.url), `${JSON.stringify(snapshot, null, 2)}\n`);
writeFileSync(
  new URL('../src/game/minigames/generated/pokemonJump.ts', import.meta.url),
  `// Generated by scripts/fetch-frlg-minigames.mjs from ${snapshot.source}.
// Do not edit: re-run the script.

/** How a kind jumps in FireRed's Pokémon Jump: its arc is \`POKEMON_JUMP_ARCS\`. */
export type JumpType = 'fast' | 'normal' | 'slow';

/** The height of a jump's top, in pixels above the ground (\`JUMP_PEAK\`). */
export const POKEMON_JUMP_PEAK = ${snapshot.jumpPeak};

/** The most a game can score (\`MAX_JUMP_SCORE\`). */
export const POKEMON_JUMP_MAX_SCORE = ${snapshot.maxScore};

/** The Kanto kinds FireRed lets jump, and how each jumps (\`sPokeJumpMons\`). */
export const POKEMON_JUMP_MONS: Readonly<Record<string, JumpType>> = {
${mons.map(({ species, type }) => `  '${species}': '${type}',`).join('\n')}
};

/** A jump's height frame by frame, after the four frames it takes to leave the ground (\`sJumpOffsets\`). */
export const POKEMON_JUMP_ARCS: Readonly<Record<JumpType, readonly number[]>> = {
${Object.entries(arcs)
  .map(([type, arc]) => `  ${type}: [${arc.join(', ')}],`)
  .join('\n')}
};

/** The vine's speeds through a stage, up and then back down (\`sVineBaseSpeeds\`). */
export const POKEMON_JUMP_VINE_SPEEDS = [${snapshot.vineBaseSpeeds.join(', ')}] as const;

/** How many swings a speed is held for, less two (\`sVineSpeedDelays\`). */
export const POKEMON_JUMP_VINE_DELAYS = [${snapshot.vineSpeedDelays.join(', ')}] as const;

/** The bonus for this many jumpers at the top of their jumps together (\`sScoreBonuses\`). */
export const POKEMON_JUMP_BONUSES = [${snapshot.scoreBonuses.join(', ')}] as const;

/** The scores that win berries, and how many (\`sPrizeQuantityData\`). */
export const POKEMON_JUMP_PRIZES = [
${prizes.map(({ score, quantity }) => `  { score: ${score}, quantity: ${quantity} },`).join('\n')}
] as const;
`,
);
console.log(`${mons.length} jumpers, arcs ${Object.entries(arcs).map(([t, a]) => `${t} ${a.length}`).join(', ')}`);
