// Reads where FireRed/LeafGreen stands each of Kanto's original 151 on the
// battlefield into `src/game/pokemon/generated/battlePicCoords.ts`.
//
//   node scripts/fetch-frlg-pic-coords.mjs
//
// A battle picture is a 64x64 frame with the Pokemon drawn somewhere inside it,
// and FireRed does not stand the frame on the ground: it moves each species
// down by its own `y_offset` - the empty rows under the drawing - so every
// front picture's feet land on one line on the foe's platform and every back
// picture's base on the top of the text box (`GetBattlerSpriteDefault_Y` in
// pret's `battle_gfx_sfx_util.c`). A Pokemon that flies or floats is then
// lifted off the foe's line by `gEnemyMonElevation`. Drawing every frame at
// one centre instead stood a Bulbasaur sixteen rows above its own platform.
//
// The three tables come from pret/pokefirered, pinned at the commit every other
// FireRed rule here is read from; nothing from pret is committed but these
// numbers. The sprites themselves are PokeAPI's rip of the same pictures
// (`scripts/fetch-pokemon-sprites.mjs`), so the offsets are the empty rows of
// the files the game draws.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const COMMIT = '037335f';
const BASE = `https://raw.githubusercontent.com/pret/pokefirered/${COMMIT}/src/data/pokemon_graphics`;
const out = join(here, '..', 'src', 'game', 'pokemon', 'generated', 'battlePicCoords.ts');

const species = JSON.parse(
  await readFile(join(here, '..', 'tools', 'species', 'frlg-species.json'), 'utf8'),
).species;

/** `nidoran-f` -> `SPECIES_NIDORAN_F`, `mr-mime` -> `SPECIES_MR_MIME`. */
const constantOf = (name) => `SPECIES_${name.toUpperCase().replace(/-/g, '_')}`;

const download = async (file) => {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const response = await fetch(`${BASE}/${file}`);
    if (response.ok) return response.text();
    await new Promise((resolve) => setTimeout(resolve, 500 * (attempt + 1)));
  }
  throw new Error(`could not fetch ${file}`);
};

/** Every `[SPECIES_X] = { ... .y_offset = n ... }` in a coordinates table. */
const offsetsIn = (text) => {
  const offsets = new Map();
  for (const match of text.matchAll(/\[(SPECIES_\w+)\]\s*=\s*\{[^}]*?\.y_offset\s*=\s*(\d+)/g)) {
    offsets.set(match[1], Number(match[2]));
  }
  return offsets;
};

const front = offsetsIn(await download('front_pic_coordinates.h'));
const back = offsetsIn(await download('back_pic_coordinates.h'));
const elevation = new Map(
  [...(await download('enemy_mon_elevation.h')).matchAll(/\[(SPECIES_\w+)\]\s*=\s*(\d+)/g)].map((m) => [m[1], Number(m[2])]),
);

const rows = species.map(({ dexId, name }) => {
  const constant = constantOf(name);
  if (!front.has(constant) || !back.has(constant)) {
    throw new Error(`pret has no picture coordinates for ${constant}`);
  }
  return `  ${dexId}: [${front.get(constant)}, ${back.get(constant)}, ${elevation.get(constant) ?? 0}],`;
});

await writeFile(
  out,
  `// Generated by scripts/fetch-frlg-pic-coords.mjs from pret/pokefirered ${COMMIT}
// (\`gMonFrontPicCoords\`, \`gMonBackPicCoords\`, \`gEnemyMonElevation\`). Do not edit: re-run the script.

/**
 * Where FireRed stands each species in battle, by national dex number:
 * [front picture's empty rows under its feet, back picture's empty rows under
 * it, how far the foe's picture is lifted off its platform].
 */
export const BATTLE_PIC_COORDS: Readonly<Record<number, readonly [number, number, number]>> = {
${rows.join('\n')}
};
`,
);
console.log(`wrote ${rows.length} species to ${out}`);
