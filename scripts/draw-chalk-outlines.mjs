#!/usr/bin/env node
// Traces what Brock will build in each bay of his workshop into the chalk line he
// draws on the floor where it will stand (`src/game/base/chalk.ts`): the piece's
// own art off `frlg-base.png`, kept where its outline or a hard edge inside it runs,
// so the chalk is the very thing to come and nobody draws it twice. Writes
// `src/game/base/generated/chalkOutlines.ts`; run it again if a piece is re-cut.
//
//   node scripts/draw-chalk-outlines.mjs
import { writeFileSync } from 'node:fs';
import { readPng } from '../tools/tileset/tileSheet.mjs';

const PIECES = {
  'warehouse.terminals': { column: 0, row: 12, width: 2, height: 3 },
  'warehouse.generator': { column: 0, row: 5, width: 3, height: 3 },
  'warehouse.crate': { column: 0, row: 17, width: 2, height: 2 },
  'lab.machineLifted': { column: 11, row: 9, width: 2, height: 3 },
  'warehouse.monitorDesk': { column: 3, row: 5, width: 2, height: 4 },
};

/** How far apart two neighbours' brightness must be to be a line, out of 255. */
const EDGE = 74;

const sheet = readPng(new URL('../public/assets/frlg-base.png', import.meta.url));
const at = (x, y) => {
  if (x < 0 || y < 0 || x >= sheet.width || y >= sheet.height) return null;
  const i = (y * sheet.width + x) * 4;
  return sheet.data[i + 3] === 0 ? null : 0.3 * sheet.data[i] + 0.59 * sheet.data[i + 1] + 0.11 * sheet.data[i + 2];
};

const lines = [
  '// Generated by scripts/draw-chalk-outlines.mjs from public/assets/frlg-base.png. Do not edit.',
  '',
  '/** Each piece as rows of its own pixels, `#` where the chalk line runs and `.` where it does not. */',
  'export const CHALK_OUTLINES: Readonly<Record<string, readonly string[]>> = {',
];
for (const [name, piece] of Object.entries(PIECES)) {
  const left = piece.column * 16;
  const top = piece.row * 16;
  const rows = [];
  for (let y = top; y < top + piece.height * 16; y += 1) {
    let row = '';
    for (let x = left; x < left + piece.width * 16; x += 1) {
      const here = at(x, y);
      if (here === null) {
        row += '.';
        continue;
      }
      // A cut piece's edge is its outline; inside it, only a hard change of
      // brightness to the right or below, so a shaded surface stays clear.
      const inPiece = (nx, ny) => nx >= left && ny >= top && nx < left + piece.width * 16 && ny < top + piece.height * 16;
      const neighbours = [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]];
      const outline = neighbours.some(([nx, ny]) => !inPiece(nx, ny) || at(nx, ny) === null);
      const hard = [[x + 1, y], [x, y + 1]].some(([nx, ny]) => inPiece(nx, ny) && at(nx, ny) !== null && Math.abs(at(nx, ny) - here) >= EDGE);
      row += outline || hard ? '#' : '.';
    }
    rows.push(row);
  }
  lines.push(`  ${JSON.stringify(name)}: [`, ...rows.map((row) => `    '${row}',`), '  ],');
}
lines.push('};', '');
writeFileSync(new URL('../src/game/base/generated/chalkOutlines.ts', import.meta.url), lines.join('\n'));
