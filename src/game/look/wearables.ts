function toWearable([id, name, kind, piece, rarity, price, note, dye]: Row): Wearable {
  return {
    id,
    name,
    kind,
    piece,
    rarity,
    note,
    ...(dye ? { dye } : {}),
    ...(typeof price === 'number' ? { price } : {}),
    ...(price !== null && typeof price === 'object' ? { barter: price } : {}),
  };
}

export const WEARABLES: readonly Wearable[] = [...ROWS, ...DYED, ...RAID_FINDS].map(toWearable);

const BY_ID = new Map(WEARABLES.map((wearable) => [wearable.id, wearable]));

/** Ids a save or a harbour message may still carry for a piece that has since been renamed. */
export const RETIRED_WEARABLE_IDS: Readonly<Record<string, string>> = {};

export function wearableById(id: string): Wearable | undefined {
  return BY_ID.get(Object.hasOwn(RETIRED_WEARABLE_IDS, id) ? RETIRED_WEARABLE_IDS[id] : id);
}

export function isWearableId(id: unknown): id is string {
  return typeof id === 'string' && wearableById(id) !== undefined;
}

/** Which of the look's slots a piece is worn in. */
export function slotOf(wearable: Wearable): 'head' | 'top' | 'legs' | 'body' {
  return WEARABLE_PIECES[wearable.piece].slot;
}

/** Every player owns these from the start, so any look can be made whole. */
export const STARTER_WEARABLES: readonly string[] = WEARABLES.filter(
  (wearable) => wearable.rarity === 'starter',
).map((wearable) => wearable.id);
