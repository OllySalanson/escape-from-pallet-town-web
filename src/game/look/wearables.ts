/**
 * The boutique's catalogue: everything a player can wear, what it costs and
 * how rare it is. Every piece is cut from a FireRed figure by
 * `scripts/cut-frlg-wearables.mjs` (`generated/wearablePieces.ts`), so a cap
 * here is a cap somebody in Kanto wears; a colour variant is the same piece
 * dyed in one of FireRed's own colour ramps (`WEARABLE_RAMPS`), which is how
 * the game itself makes a camper out of a youngster.
 *
 * The economy is the captain's standing rules, and the tiers say how each is
 * kept:
 *
 *  - **Everyday** and **smart** pieces are sold for Pokédollars, which is the
 *    money sink: a raid brings home tens of Pokédollars (`hub/trader.ts`), so a
 *    cap is a raid or two and a good coat is a month of them.
 *  - **Fine** pieces are the long sink - the dearest money can buy.
 *  - **Barter** pieces are the famous people's own looks - the gym leaders, the
 *    Elite Four, the champions - and are never sold for money: they are paid
 *    for in found goods, as Bill's best things are.
 *  - **Raid** pieces are legendary-themed and shiny-coloured, and are only ever
 *    found on a raid; the boutique shows them and cannot sell them.
 *
 * A piece's `id` is wire format - it is what a save's wardrobe and a harbour
 * message carry - so renaming one is a row in `RETIRED_WEARABLE_IDS`, never an
 * edit of an id.
 */
import {
  WEARABLE_PIECES,
  type WearablePieceId,
  type WearableRamp,
} from './generated/wearablePieces';

/** The name over the shop door, and on every screen inside it. */
export const BOUTIQUE_NAME = 'THE HARBOUR BOUTIQUE';

/** What a piece is, for the shop's shelves. The slot it is worn in follows from its piece. */
export type WearableKind = 'hat' | 'hair' | 'top' | 'legs' | 'outfit';

export type WearableRarity = 'starter' | 'everyday' | 'smart' | 'fine' | 'barter' | 'raid';

/** A dye: one ramp of the piece swapped for another, shade for shade. */
export interface WearableDye {
  readonly from: WearableRamp;
  readonly to: DyeRamp;
}

/**
 * The colours a dye may use. FireRed's own ramps, and five that FireRed keeps
 * for its shiny and legendary Pokémon rather than its people, which are only
 * ever found on a raid.
 */
export const RAID_RAMPS = {
  ice: [0xdeeeff, 0x8cb5e6, 0x42528c],
  jet: [0x6b6b7b, 0x31313a, 0x101018],
  gold: [0xffe684, 0xe6ad29, 0x845210],
  flame: [0xffad42, 0xe65a18, 0x841000],
  psychic: [0xd6b5ff, 0x9473d6, 0x4a3184],
} as const;

export type DyeRamp = WearableRamp | keyof typeof RAID_RAMPS;

/** Found goods a barter piece asks for, by item id. Never money. */
export type BarterPrice = Readonly<Record<string, number>>;

export interface Wearable {
  readonly id: string;
  readonly name: string;
  readonly kind: WearableKind;
  readonly piece: WearablePieceId;
  readonly dye?: WearableDye;
  readonly rarity: WearableRarity;
  /** Pokédollars, for everyday, smart and fine pieces. */
  readonly price?: number;
  /** Found goods, for barter pieces. */
  readonly barter?: BarterPrice;
  /** One line on who wears it, for the shop. */
  readonly note: string;
}

type Row = readonly [
  id: string,
  name: string,
  kind: WearableKind,
  piece: WearablePieceId,
  rarity: WearableRarity,
  price: number | BarterPrice | null,
  note: string,
  dye?: WearableDye,
];

